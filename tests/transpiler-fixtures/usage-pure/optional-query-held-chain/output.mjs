import _includes from "@core-js/pure/actual/instance/includes";
export function read(source) {
  const a = source?.next;
  const b = a?.next;
  const c = b?.next;
  const d = c?.next;
  const e = d?.next;
  const f = e?.next;
  const g = f?.next;
  const h = g?.next;
  return h == null ? void 0 : _includes(h).call(h, 1);
}
// a host-level claim written ahead of a nested leaf the twin splits out extracts once, beside a twin that reads its
// hop once - behind a default, a symbol key or a second host claim alike - and an assignment twin reads its hop once
// whatever parentheses wrap the statement
function rows(box) {
  const { includes, y: { other: { q }, at } } = box;
  const { keys = null, z: { more: { r }, flat } } = box;
  const { [Symbol.iterator]: it, w: { past: { s }, find } } = box;
  const { entries, values, v: { next: { n }, fill } } = box;
  let findLast, findLastIndex, copyWithin, findIndex;
  (({ u: { findLast, findLastIndex } } = box));
  (({ copyWithin, findIndex } = box.t));
  return [
    [includes, q, at],
    [keys, r, flat],
    [it, s, find],
    [entries, values, n, fill],
    [findLast, findLastIndex, copyWithin, findIndex],
  ];
}
use(rows);
